def set_text(paragraph, text):
    """Replace paragraph text while keeping the paragraph style in place."""
    if paragraph.runs:
        paragraph.runs[0].text = text
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(text)


def set_cell(cell, text):
    paragraph = cell.paragraphs[0]
    set_text(paragraph, text)
    for extra in cell.paragraphs[1:]:
        set_text(extra, "")


def set_row(row, values):
    for cell, value in zip(row.cells, values):
        set_cell(cell, value)


def append_row_if_missing(table, key, values):
    existing = [" ".join(row.cells[0].text.split()) for row in table.rows]
    if key in existing:
        return
    row = table.add_row()
    set_row(row, values)


